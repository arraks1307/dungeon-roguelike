using Godot;

namespace Roguelike;

/// <summary>Житель лагеря: его находят в подземелье, а после спасения он открывает постройку.</summary>
public record Resident(string Id, string Name, string Rescue, string Camp);

/// <summary>Правило сделки, которое нельзя выразить числами.</summary>
public enum PactRule
{
    None,
    WeakPotions, // зелья лечат вдвое слабее
    Poverty,     // золота достаётся вдвое меньше
    Bloodlust,   // враги этажа на 15% крепче
    Haste,       // способности заряжаются на 1 атаку быстрее
}

/// <summary>Сделка с подземельем: сила на весь забег, за которую придётся платить до его конца.</summary>
public record Pact(string Name, string Offer, Stats Stats, PactRule Rule = PactRule.None);

public static class Pacts
{
    public static readonly Pact[] All =
    {
        new("Жертва крови", "+3 к атаке, но −10 к здоровью", new Stats(Attack: 3, MaxHp: -10)),
        new("Стеклянная пушка", "+25% шанс крита, но −2 к защите", new Stats(Crit: 25, Defense: -2)),
        new("Договор голода", "+2 лечения за удар, но зелья лечат вдвое слабее", new Stats(Lifesteal: 2), PactRule.WeakPotions),
        new("Обет нищеты", "+2 к защите, но золота вдвое меньше", new Stats(Defense: 2), PactRule.Poverty),
        new("Слепая вера", "+4 к атаке, но −3 к обзору", new Stats(Attack: 4, Vision: -3)),
        new("Кровавая охота", "+3 к атаке и +5 к здоровью, но враги на 15% крепче", new Stats(Attack: 3, MaxHp: 5), PactRule.Bloodlust),
        new("Тлеющая кожа", "+3 огня и +3 шипов, но −1 к защите", new Stats(Defense: -1, Thorns: 3, FireDamage: 3)),
        new("Цена спешки", "способности заряжаются на 1 атаку быстрее, но −8 к здоровью", new Stats(MaxHp: -8), PactRule.Haste),
    };

    public static Pact Find(string name) => System.Array.Find(All, pact => pact.Name == name);
}

